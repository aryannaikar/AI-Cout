"""
Pydantic data models for Conflict Detection in AI Court of India.
"""

from __future__ import annotations

from enum import Enum
from pydantic import BaseModel, Field


class ConflictCategory(str, Enum):
    WITNESS_CONTRADICTION = "witness_contradiction"
    EVIDENCE_CONTRADICTION = "evidence_contradiction"
    PROSECUTION_VS_DEFENSE = "prosecution_vs_defense"
    CONFLICTING_LEGAL_PROVISIONS = "conflicting_legal_provisions"
    FACTUAL_INCONSISTENCY = "inconsistent_factual_claims"
    UNSUPPORTED_ASSERTION = "unsupported_assertion"


class ConflictSeverity(str, Enum):
    LOW = "low_minor_discrepancy"
    MEDIUM = "medium_material_inconsistency"
    HIGH = "high_serious_contradiction"
    FATAL_TO_CHARGE = "fatal_to_charge_irreconcilable"


class Conflict(BaseModel):
    """Represents an unresolved contradiction or inconsistency discovered in the courtroom record."""

    conflict_id: str = Field(description="Unique conflict identifier (e.g. 'CONF-01').")
    category: ConflictCategory = Field(description="Category of the detected discrepancy.")
    statement_a: str = Field(description="First statement or factual claim.")
    statement_b: str = Field(description="Opposing statement or contradictory evidentiary finding.")
    sources: list[str] = Field(
        default_factory=list,
        description="Originating sources (e.g. ['PW-1 testimony', 'Ex. P-3 forensic report']).",
    )
    severity: ConflictSeverity = Field(description="Assessed gravity of the contradiction.")
    explanation: str = Field(description="Analytical explanation of why these claims are mutually irreconcilable.")
    impact_on_case: str = Field(description="Potential impact on the prosecution theory or defense plea.")
    resolution_required: bool = Field(
        default=True,
        description="Explicit flag ensuring this conflict is transmitted to the Judge for judicial resolution.",
    )


class ConflictReport(BaseModel):
    """Complete report generated by the Conflict Detection Agent."""

    case_id: str = Field(description="Case identifier.")
    total_conflicts: int = Field(description="Total count of discovered conflicts.")
    conflicts: list[Conflict] = Field(
        default_factory=list,
        description="List of all detected conflicts across the trial record.",
    )
    critical_conflicts_count: int = Field(
        default=0,
        description="Count of high or fatal contradictions that directly affect proof beyond reasonable doubt.",
    )
    summary: str = Field(
        description="Comprehensive summary of contradictory elements in the evidentiary record.",
    )
